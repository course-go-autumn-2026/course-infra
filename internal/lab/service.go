func ensureEnvWritable(path string) error {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect .env: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return fmt.Errorf("%w: existing .env is not a regular generated file; move it aside and retry", cluster.ErrConflict)
	}
	file, err := os.Open(path) // #nosec G304 -- explicit project-local path.
	if err != nil {
		return fmt.Errorf("inspect .env: %w", err)
	}
	defer func() { _ = file.Close() }()
	line, readErr := bufio.NewReader(file).ReadString('\n')
	if readErr != nil && !errors.Is(readErr, io.EOF) {
		return fmt.Errorf("inspect .env marker: %w", readErr)
	}
	if strings.TrimSuffix(line, "\n") != envMarker {
		return fmt.Errorf("%w: existing .env is not generated by tripgoctl; move it aside and run tripgoctl environment start again", cluster.ErrConflict)
	}
	return nil
}

func ensureTripgoWritable(path string) error {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect .tripgo: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return fmt.Errorf("%w: existing .tripgo is not a directory; move it aside and retry", cluster.ErrConflict)
	}
	rendered := filepath.Join(path, "rendered")
	renderedInfo, err := os.Lstat(rendered)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect .tripgo/rendered: %w", err)
	}
	if renderedInfo.Mode()&os.ModeSymlink != 0 || !renderedInfo.IsDir() {
		return fmt.Errorf("%w: existing .tripgo/rendered is not a directory; move it aside and retry", cluster.ErrConflict)
	}
	return nil
}

func writeEnv(path string, config configenv.Config, version string) error {
	if err := ensureEnvWritable(path); err != nil {
		return err
	}
	var content strings.Builder
	fmt.Fprintln(&content, envMarker)
	fmt.Fprintln(&content, "# Source: environment.toml")
	fmt.Fprintf(&content, "# Lab: %d\n", config.Lab)
	fmt.Fprintf(&content, "# Generator: tripgoctl %s\n", version)
	for _, variable := range config.EnvironmentVariables() {
		fmt.Fprintf(&content, "%s=%s\n", variable.Name, variable.Value)
	}
	return atomicWrite(path, []byte(content.String()), 0o600)
}

func atomicWrite(path string, content []byte, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".tripgo-env-*")
	if err != nil {
		return fmt.Errorf("create temporary .env: %w", err)
	}
	temporaryPath := temporary.Name()
	defer func() { _ = os.Remove(temporaryPath) }()
	defer func() { _ = temporary.Close() }()
	if err := temporary.Chmod(mode); err != nil {
		return err
	}
	if _, err := temporary.Write(content); err != nil {
		return err
	}
	if err := temporary.Sync(); err != nil {
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	if err := os.Rename(temporaryPath, path); err != nil {
		return fmt.Errorf("install .env: %w", err)
	}
	directory, err := os.Open(filepath.Dir(path)) // #nosec G304 -- explicit project-local directory.
	if err != nil {
		return fmt.Errorf("open .env directory for sync: %w", err)
	}
	defer func() { _ = directory.Close() }()
	if err := directory.Sync(); err != nil {
		return fmt.Errorf("sync .env directory: %w", err)
	}
	return nil
}

func removeGenerated(path string, directory bool) error {
	if directory {
		info, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return fmt.Errorf("inspect generated directory: %w", err)
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return nil
		}
		rendered := filepath.Join(path, "rendered")
		renderedInfo, renderedErr := os.Lstat(rendered)
		if renderedErr == nil && renderedInfo.Mode()&os.ModeSymlink == 0 && renderedInfo.IsDir() {
			if err := os.RemoveAll(rendered); err != nil {
				return err
			}
		} else if renderedErr != nil && !errors.Is(renderedErr, os.ErrNotExist) {
			return fmt.Errorf("inspect generated rendered directory: %w", renderedErr)
		}
		entries, err := os.ReadDir(path)
		if err != nil {
			return fmt.Errorf("inspect generated directory contents: %w", err)
		}
		if len(entries) == 0 {
			return os.Remove(path)
		}
		return nil
	}
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect generated .env: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return nil
	}
	file, err := os.Open(path) // #nosec G304 -- explicit project-local path.
	if err != nil {
		return fmt.Errorf("inspect generated .env: %w", err)
	}
	line, readErr := bufio.NewReader(file).ReadString('\n')
	closeErr := file.Close()
	if readErr != nil && !errors.Is(readErr, io.EOF) {
		return fmt.Errorf("inspect generated .env marker: %w", readErr)
	}
	if closeErr != nil {
		return fmt.Errorf("close generated .env: %w", closeErr)
	}
	if strings.TrimSuffix(line, "\n") != envMarker {
		return nil
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

