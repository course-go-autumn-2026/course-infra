func verifyRedpandaResources(ctx context.Context, client dynamic.Interface, lab int, namespace, clusterID string) error {
	topicsConfig, err := client.Resource(configMapResource).Namespace(namespace).Get(ctx, "redpanda-topics", metav1.GetOptions{})
	if apierrors.IsNotFound(err) {
		return fmt.Errorf("%w: redpanda-topics is absent in %s; run tripgoctl environment start", cluster.ErrPrerequisite, namespace)
	}
	if err != nil {
		return fmt.Errorf("inspect redpanda-topics: %w", err)
	}
	if err := verifyResourceOwnership(topicsConfig, lab, namespace, clusterID); err != nil {
		return err
	}
	data, found, err := unstructured.NestedStringMap(topicsConfig.Object, "data")
	if err != nil || !found {
		return fmt.Errorf("%w: redpanda-topics ConfigMap data is invalid", cluster.ErrConflict)
	}
	expectedData := redpandaconfig.ConfigMapData()
	if len(data) != len(expectedData) || data["topics"] != expectedData["topics"] || data["reconcile.sh"] != expectedData["reconcile.sh"] {
		return fmt.Errorf("%w: redpanda-topics ConfigMap does not match the managed reconciliation contract", cluster.ErrConflict)
	}

	redpandaService, err := client.Resource(serviceResource).Namespace(namespace).Get(ctx, "redpanda", metav1.GetOptions{})
	if apierrors.IsNotFound(err) {
		return fmt.Errorf("%w: redpanda is absent in %s; run tripgoctl environment start", cluster.ErrPrerequisite, namespace)
	}
	if err != nil {
		return fmt.Errorf("inspect redpanda service: %w", err)
	}
	if err := verifyResourceOwnership(redpandaService, lab, namespace, clusterID); err != nil {
		return err
	}
	statefulSet, err := client.Resource(statefulSetResource).Namespace(namespace).Get(ctx, "redpanda", metav1.GetOptions{})
	if err != nil {
		return fmt.Errorf("inspect Redpanda advertised listener: %w", err)
	}
	containers, _, _ := unstructured.NestedSlice(statefulSet.Object, "spec", "template", "spec", "containers")
	args := []any(nil)
	if len(containers) > 0 {
		container, _ := containers[0].(map[string]any)
		args, _, _ = unstructured.NestedSlice(container, "args")
	}
	port, _ := catalog.PortByName(lab, "redpanda-kafka")
	advertised := "--advertise-kafka-addr=internal://redpanda:9092,external://localhost:" + fmt.Sprint(port.HostPort)
	advertisedFound := false
	for _, arg := range args {
		advertisedFound = advertisedFound || arg == advertised
	}
	if !advertisedFound {
		return fmt.Errorf("%w: Redpanda advertised Kafka listener does not match lab %d host port", cluster.ErrConflict, lab)
	}
	claims, err := client.Resource(pvcResource).Namespace(namespace).List(ctx, metav1.ListOptions{LabelSelector: "app.kubernetes.io/managed-by=tripgoctl,tripgo.course/environment=" + namespace})
	if err != nil {
		return fmt.Errorf("list Redpanda persistent claims: %w", err)
	}
	redpandaClaims := 0
	for i := range claims.Items {
		claim := &claims.Items[i]
		if strings.HasPrefix(claim.GetName(), "data-redpanda-") {
			redpandaClaims++
			if err := verifyResourceOwnership(claim, lab, namespace, clusterID); err != nil {
				return err
			}
		}
	}
	if redpandaClaims != 1 {
		return fmt.Errorf("%w: expected one owned Redpanda PVC, found %d", cluster.ErrConflict, redpandaClaims)
	}
	return nil
}

